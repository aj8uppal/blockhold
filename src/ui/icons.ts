/** tones: the body is drawn whole, then each overlay is laid on top of it */
const OVERLAY: Record<string, string> = {
  '+': 'rgba(255,255,255,.42)',
  o: 'rgba(0,0,0,.24)',
  x: 'rgba(0,0,0,.5)',
}

const SIZE = 16

function compile(rows: string[]): string {
  const height = rows.length
  const width = Math.max(...rows.map(r => r.length))
  let minX = width, maxX = -1, minY = height, maxY = -1
  rows.forEach((row, y) => [...row].forEach((ch, x) => {
    if (ch === '.' || ch === ' ') return
    minX = Math.min(minX, x); maxX = Math.max(maxX, x); minY = Math.min(minY, y); maxY = Math.max(maxY, y)
  }))
  const w = maxX - minX + 1, h = maxY - minY + 1
  // a drawing wider than the grid scales the viewBox rather than clipping
  const box = Math.max(SIZE, w, h)
  const ox = Math.floor((box - w) / 2) - minX, oy = Math.floor((box - h) / 2) - minY
  const paths: Record<string, string> = { '#': '', '+': '', o: '', x: '' }
  rows.forEach((row, y) => {
    let x = 0
    while (x < row.length) {
      const ch = row[x]
      if (ch === '.' || ch === ' ') { x++; continue }
      // every marked cell is body; overlays run separately so a lit or shaded
      // face is the body's colour, lightened or darkened, on any background
      let end = x
      while (end < row.length && row[end] !== '.' && row[end] !== ' ') end++
      paths['#'] += `M${x + ox} ${y + oy}h${end - x}v1h-${end - x}z`
      for (let i = x; i < end;) {
        const tone = row[i]
        let j = i
        while (j < end && row[j] === tone) j++
        if (tone in OVERLAY) paths[tone] += `M${i + ox} ${y + oy}h${j - i}v1h-${j - i}z`
        i = j
      }
      x = end
    }
  })
  let svg = `<path fill="currentColor" d="${paths['#']}"/>`
  for (const tone of ['+', 'o', 'x']) if (paths[tone]) svg += `<path fill="${OVERLAY[tone]}" d="${paths[tone]}"/>`
  return `<svg class="ico ico-NAME CLS" viewBox="0 0 ${box} ${box}" aria-hidden="true" focusable="false" shape-rendering="crispEdges">${svg}</svg>`
}

const compiled = new Map<string, string>()
for (const [name, rows] of Object.entries(RAW)) compiled.set(name, compile(rows))

