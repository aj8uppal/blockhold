/**
 * Blockhold's icon set: every symbol is drawn on a 16-block grid.
 *
 * The world is built from voxels, so the interface is built from pixels: each
 * icon below is hand-placed as ASCII and turned into one SVG path per tone at
 * load time. Four marks are understood:
 *
 *   #  the body          — currentColor
 *   +  a lit face        — the body under a pale overlay
 *   o  a shaded face     — the body under a dark overlay
 *   x  a cut or engraving — a deep overlay, for eyes, seams and rims
 *
 * Shapes are centred on their bounding box, so a grid only has to describe
 * the drawing, not its margins. Colour comes from CSS (`color`), size from
 * `font-size` (every icon is 1em square).
 */

