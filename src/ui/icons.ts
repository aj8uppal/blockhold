/** render an icon by name; extra classes are appended (e.g. 'plain' or 'vet') */
export function icon(name: string, cls = ''): string {
  const svg = compiled.get(name)
  if (!svg) return ''
  return svg.replace('ico-NAME', `ico-${name}`).replace(' CLS', cls ? ` ${cls}` : '')
}
